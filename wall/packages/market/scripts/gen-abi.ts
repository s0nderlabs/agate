// Regenerates src/abi.ts from a Foundry build of the market contracts (BOTS-SPEC 0.2 item 5): the abi arrays of
// AgateFactory, AgateSeries, AgateToken, AgateRouter, AgateDollar and IKuruRouter as `as const` exports, plus
// agateIndexAbi re-exported from @agate/report/abi. AGATE_FORGE_OUT: the forge out folder (default contracts/out).
// Build first: cd contracts && FOUNDRY_OUT=$HOME/.agate-build/<role>/out FOUNDRY_CACHE_PATH=$HOME/.agate-build/<role>/cache forge build
import { join } from "node:path";

export const ABI_SOURCES = [
  ["agateFactoryAbi", "AgateFactory"],
  ["agateSeriesAbi", "AgateSeries"],
  ["agateTokenAbi", "AgateToken"],
  ["agateRouterAbi", "AgateRouter"],
  ["agateDollarAbi", "AgateDollar"],
  ["iKuruRouterAbi", "IKuruRouter"],
] as const;

export function forgeOut(): string {
  return process.env.AGATE_FORGE_OUT ?? join(import.meta.dir, "../../../../contracts/out");
}

export async function render(out: string): Promise<string> {
  let body = "// GENERATED by scripts/gen-abi.ts from a Foundry build of contracts/src/market. Do not edit.\n";
  for (const [name, contract] of ABI_SOURCES) {
    const { abi } = (await Bun.file(join(out, `${contract}.sol/${contract}.json`)).json()) as { abi: unknown[] };
    body += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  }
  body += 'export { agateIndexAbi } from "@agate/report/abi";\n';
  return body;
}

if (import.meta.main) {
  const dest = join(import.meta.dir, "../src/abi.ts");
  await Bun.write(dest, await render(forgeOut()));
  console.log(`wrote ${dest}`);
}
